def test_detects_the_iphone_composite_device_and_its_driver():
    assert usbdriver.connected_iphones(DEVICES) == [('Apple Mobile Device USB Composite Device', 0x12A8, False)]
    assert usbdriver.connected_iphones(LIBUSB_DEVICES) == [('iPhone (Composite Parent)', 0x12A8, True)]


def test_only_libusb_packages_for_apple_devices_are_restorable():
    assert usbdriver.libusb_packages(DRIVERS) == ['oem7.inf']


@pytest.fixture
def wdi(tmp_path, monkeypatch):
    tool = tmp_path / 'wdi-simple.exe'
    tool.write_bytes(b'')
    monkeypatch.setenv('MIRRORDESK_WDI_SIMPLE', str(tool))
    monkeypatch.setattr(usbdriver, '_on_windows', lambda: True)
    return tool


def test_install_runs_wdi_simple_once_for_the_plugged_in_phone(wdi, tmp_path):
    calls = []

    def run_elevated(command, log):
        calls.append(command)
        Path(log).write_text('Extracting driver files...\n  Success\nInstalling driver(s)...\n  Success\n')
        return 0
    message = usbdriver.install(tmp_path, run_elevated=run_elevated,
                                phones=lambda: [('Apple Mobile Device USB Composite Device', 0x12A8, False)])
    assert len(calls) == 1, 'one elevated run = one Windows permission prompt'
    command = calls[0]
    assert command.startswith(f'"{wdi}"')
    for part in ('--vid 0x05AC', '--pid 0x12A8', '--type 1', f'--inf {usbdriver.INF_NAME}',
                 f'--name "{usbdriver.DEVICE_NAME}"'):
        assert part in command
    assert '--iid' not in command, 'the whole composite device, not one interface'
    assert 'Unplug the phone' in message


def test_install_reports_failure_with_the_log(wdi, tmp_path):
    def run_elevated(command, log):
        Path(log).write_text('Extracting driver files...\n  Success\nInstalling driver(s)...\n  Failed: no device\n')
        return 1
    with pytest.raises(usbdriver.DriverError, match='Failed: no device'):
        usbdriver.install(tmp_path, run_elevated=run_elevated, phones=lambda: [('iPhone', 0x12A8, False)])


def test_install_needs_a_phone_and_skips_an_installed_driver(wdi, tmp_path):
    never = lambda command, log: pytest.fail('must not run')  # noqa: E731
    with pytest.raises(usbdriver.DriverError, match='No iPhone'):
        usbdriver.install(tmp_path, run_elevated=never, phones=lambda: [])
    assert 'already uses' in usbdriver.install(tmp_path, run_elevated=never, phones=lambda: [('iPhone', 0x12A8, True)])


def test_declined_permission_changes_nothing(wdi, tmp_path):
    def run_elevated(command, log):
        raise usbdriver.DriverError('Windows permission was not given, so nothing was changed.')
    with pytest.raises(usbdriver.DriverError, match='permission'):
        usbdriver.install(tmp_path, run_elevated=run_elevated, phones=lambda: [('iPhone', 0x12A8, False)])


def test_restore_removes_only_apple_libusb_packages(wdi, tmp_path, monkeypatch):
    state = {'packages': ['oem7.inf', 'oem75.inf']}
    monkeypatch.setattr(usbdriver, 'libusb_packages', lambda text=None: list(state['packages']))
    commands = []

    def run_elevated(command, log):
        commands.append(command)
        state['packages'] = []
        return 0
    assert "Apple's driver is back" in usbdriver.restore(tmp_path, run_elevated=run_elevated)
    assert commands == ['pnputil /delete-driver oem7.inf /uninstall /force & '
                        'pnputil /delete-driver oem75.inf /uninstall /force & pnputil /scan-devices']
    assert 'Nothing to restore' in usbdriver.restore(tmp_path, run_elevated=lambda c, l: pytest.fail('no run'))


async def test_driver_buttons_are_local_only():
    from aiohttp.test_utils import TestClient, TestServer
    from mirrordesk.server import MirrorDeskServer
    import tempfile
    server = MirrorDeskServer(Path(tempfile.mkdtemp()), video_port=0, audio_port=0, start_receiver=False, usb=False,
                              android=False)
    server.usb = type('FakeUsb', (), {'status': lambda self: {}, 'driver_action': None,
                                      'start': _noop, 'stop': _noop})()
    server.access.is_local = lambda request: False
    server.hub.start = _noop
    server.hub.stop = _noop
    client = TestClient(TestServer(server.app()))
    await client.start_server()
    try:
        response = await client.post('/api/usb/driver-install', headers={'X-MirrorDesk': '1'})
        assert response.status in (401, 403), 'a remote browser can never trigger a driver change'
    finally:
        await client.close()


